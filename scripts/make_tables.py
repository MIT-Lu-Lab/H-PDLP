#!/usr/bin/env python3
"""Build the benchmark summary tables from the cuHSDLP-vs-cuPDLPx comparison CSVs.

Emits, for each suite, a headline table (solved counts + shifted geometric means)
and a table of the instances the two solvers disagree on.  Both are written as
LaTeX (booktabs) and Markdown.

Usage:
    python make_tables.py --date 20260712
    python make_tables.py --date 20260712 --suites miplib mittelmann
"""

import argparse
import csv
import math
import os

RESULT_DIR = os.path.join(os.path.dirname(__file__), "..", "result")
TABLE_DIR = os.path.join(RESULT_DIR, "tables")

SUITE_LABEL = {"miplib": "MIPLIB", "mittelmann": "Mittelmann", "small": "MIPLIB (small)"}


def parse_args():
    p = argparse.ArgumentParser(description="Build benchmark summary tables.")
    p.add_argument("--date", required=True, help="cuHSDLP result date, e.g. 20260712")
    p.add_argument("--suites", nargs="+", default=["miplib", "mittelmann"])
    p.add_argument("--output-dir", default=TABLE_DIR)
    return p.parse_args()


# Achterberg/SCIP shifted geometric mean: SGM_s(x) = exp(mean(log(xi + s))) - s.
def shifted_geomean(values, shift):
    if not values:
        return float("nan")
    return math.exp(sum(math.log(v + shift) for v in values) / len(values)) - shift


def load(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


# Same population rule as compare_solvers.py: every genuine optimization run (at
# least one solver OPTIMAL, or some solver hit the wall-clock cap).  Instances both
# solvers agree are infeasible/unbounded carry no optimum to time, so they drop out;
# a solver that failed is charged the wall-clock cap, read off the timed-out runs.
def summarize(rows):
    pop = [r for r in rows
           if "OPTIMAL" in (r["HSD_status"], r["PDLPx_status"])
           or "TIME_LIMIT" in (r["HSD_status"], r["PDLPx_status"])]
    timeouts = [float(r[f"{s}_time"]) for r in pop for s in ("HSD", "PDLPx")
                if r[f"{s}_status"] == "TIME_LIMIT"]
    cap = max(timeouts) if timeouts else None

    def charged(r, s):
        t = float(r[f"{s}_time"])
        return t if r[f"{s}_status"] == "OPTIMAL" or cap is None else cap

    stats = {"n": len(rows), "n_sgm": len(pop), "cap": cap}
    for s in ("HSD", "PDLPx"):
        times = [charged(r, s) for r in pop]
        iters = [float(r[f"{s}_iters"]) for r in pop]
        stats[s] = {
            "solved": sum(1 for r in rows if r[f"{s}_status"] == "OPTIMAL"),
            "sgm_time": shifted_geomean(times, 10),
            "sgm_iters": shifted_geomean(iters, 100),
        }
    stats["time_ratio"] = stats["HSD"]["sgm_time"] / stats["PDLPx"]["sgm_time"]
    stats["iter_ratio"] = stats["HSD"]["sgm_iters"] / stats["PDLPx"]["sgm_iters"]
    return stats


def disagreements(rows):
    out = []
    for r in rows:
        h, p = r["HSD_status"], r["PDLPx_status"]
        if h == p:
            continue
        out.append({
            "instance": r["instance"],
            "hsd_status": h, "pdlpx_status": p,
            "hsd_time": float(r["HSD_time"]), "pdlpx_time": float(r["PDLPx_time"]),
            "hsd_iters": int(r["HSD_iters"]), "pdlpx_iters": int(r["PDLPx_iters"]),
        })
    return out


def esc(s):
    return s.replace("_", r"\_")


def write_latex(path, date, per_suite):
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"% Generated by scripts/make_tables.py --date {date}\n")
        f.write("\\begin{table}[t]\n\\centering\n")
        f.write("\\caption{cuHSDLP versus cuPDLPx at $10^{-4}$ relative tolerance. "
                "Shifted geometric means use the Achterberg shifts ($s=10$ for time, "
                "$s=100$ for iterations); a solver that does not reach optimality is "
                "charged the wall-clock limit.  Ratios are cuHSDLP over cuPDLPx.}\n")
        f.write("\\label{tab:benchmark-summary}\n")
        f.write("\\begin{tabular}{lrrrrrrrrr}\n\\toprule\n")
        f.write("& & \\multicolumn{2}{c}{Solved} & \\multicolumn{3}{c}{SGM time (s)} "
                "& \\multicolumn{3}{c}{SGM iterations} \\\\\n")
        f.write("\\cmidrule(lr){3-4}\\cmidrule(lr){5-7}\\cmidrule(lr){8-10}\n")
        f.write("Suite & $n$ & cuHSDLP & cuPDLPx & cuHSDLP & cuPDLPx & ratio "
                "& cuHSDLP & cuPDLPx & ratio \\\\\n")
        f.write("\\midrule\n")
        for suite, st in per_suite.items():
            f.write("%s & %d & %d & %d & %.1f & %.1f & %.2f & %.0f & %.0f & %.2f \\\\\n" % (
                SUITE_LABEL[suite], st["n"],
                st["HSD"]["solved"], st["PDLPx"]["solved"],
                st["HSD"]["sgm_time"], st["PDLPx"]["sgm_time"], st["time_ratio"],
                st["HSD"]["sgm_iters"], st["PDLPx"]["sgm_iters"], st["iter_ratio"]))
        f.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n\n")

        f.write("\\begin{table}[t]\n\\centering\n")
        f.write("\\caption{Instances on which the two solvers reach different "
                "terminations.}\n\\label{tab:benchmark-disagreements}\n")
        f.write("\\begin{tabular}{llrlr}\n\\toprule\n")
        f.write("Instance & cuHSDLP & time (s) & cuPDLPx & time (s) \\\\\n\\midrule\n")
        for suite, st in per_suite.items():
            for d in st["disagree"]:
                f.write("%s & %s & %.1f & %s & %.1f \\\\\n" % (
                    esc(d["instance"]), esc(d["hsd_status"]), d["hsd_time"],
                    esc(d["pdlpx_status"]), d["pdlpx_time"]))
        f.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    print(f"  {path}")


def write_markdown(path, date, per_suite):
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"# Benchmark summary: cuHSDLP vs cuPDLPx ({date}, tol 1e-4)\n\n")
        f.write("| Suite | n | solved HSD | solved PDLPx | SGM time HSD (s) | "
                "SGM time PDLPx (s) | time ratio | SGM iters HSD | SGM iters PDLPx | iter ratio |\n")
        f.write("|---|---|---|---|---|---|---|---|---|---|\n")
        for suite, st in per_suite.items():
            f.write("| %s | %d | %d | %d | %.1f | %.1f | %.2fx | %.0f | %.0f | %.2fx |\n" % (
                SUITE_LABEL[suite], st["n"],
                st["HSD"]["solved"], st["PDLPx"]["solved"],
                st["HSD"]["sgm_time"], st["PDLPx"]["sgm_time"], st["time_ratio"],
                st["HSD"]["sgm_iters"], st["PDLPx"]["sgm_iters"], st["iter_ratio"]))
        f.write("\nSGM population per suite: ")
        f.write(", ".join(f"{SUITE_LABEL[s]} {st['n_sgm']}/{st['n']}"
                          + (f" (cap {st['cap']:.0f}s)" if st["cap"] else "")
                          for s, st in per_suite.items()))
        f.write("\n\n## Termination disagreements\n\n")
        f.write("| Suite | Instance | cuHSDLP | time (s) | iters | cuPDLPx | time (s) | iters |\n")
        f.write("|---|---|---|---|---|---|---|---|\n")
        for suite, st in per_suite.items():
            for d in st["disagree"]:
                f.write("| %s | %s | %s | %.1f | %d | %s | %.1f | %d |\n" % (
                    SUITE_LABEL[suite], d["instance"],
                    d["hsd_status"], d["hsd_time"], d["hsd_iters"],
                    d["pdlpx_status"], d["pdlpx_time"], d["pdlpx_iters"]))
    print(f"  {path}")


def main():
    args = parse_args()
    os.makedirs(args.output_dir, exist_ok=True)
    per_suite = {}
    for suite in args.suites:
        csv_path = os.path.join(
            RESULT_DIR, f"comparison_cuHSDLP_vs_cuPDLPx_{suite}_{args.date}.csv")
        rows = load(csv_path)
        st = summarize(rows)
        st["disagree"] = disagreements(rows)
        per_suite[suite] = st

    print(f"Writing tables for {args.date}:")
    write_latex(os.path.join(args.output_dir, f"benchmark_summary_{args.date}.tex"),
                args.date, per_suite)
    write_markdown(os.path.join(args.output_dir, f"benchmark_summary_{args.date}.md"),
                   args.date, per_suite)


if __name__ == "__main__":
    main()
