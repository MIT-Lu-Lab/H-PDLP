#!/usr/bin/env python3
"""Build the LaTeX and Markdown benchmark summary tables from the dated comparison CSVs."""
import argparse
import math
from pathlib import Path

from bench_compare import (DEFAULT_TOL, ITER_SHIFT, SOLVERS, SUITE_LABEL, TIME_SHIFT, charged_time,
                           load_comparison, sgm_population, shifted_geomean)
from common import TABLE_DIR


def summarize(rows):
    pop, cap = sgm_population(rows)
    stats = {"n": len(rows), "n_sgm": len(pop)}
    for s in SOLVERS:
        stats[s] = {
            "solved": sum(1 for r in rows if r[f"{s}_status"] == "OPTIMAL"),
            "sgm_time": shifted_geomean([charged_time(r, s, cap) for r in pop], TIME_SHIFT),
            "sgm_iters": shifted_geomean([r[f"{s}_iters"] for r in pop], ITER_SHIFT),
        }
    stats["time_ratio"] = stats["HSD"]["sgm_time"] / stats["PDLPx"]["sgm_time"]
    stats["iter_ratio"] = stats["HSD"]["sgm_iters"] / stats["PDLPx"]["sgm_iters"]
    return stats


def summary_cells(suite, st):
    """The ten values of one suite's row in the summary table."""
    return (SUITE_LABEL[suite], st["n"], st["HSD"]["solved"], st["PDLPx"]["solved"],
            st["HSD"]["sgm_time"], st["PDLPx"]["sgm_time"], st["time_ratio"],
            st["HSD"]["sgm_iters"], st["PDLPx"]["sgm_iters"], st["iter_ratio"])


def esc(s):
    return s.replace("_", r"\_")


def write_latex(path, date, tol, per_suite):
    exponent = round(math.log10(float(tol)))
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"% Generated by scripts/bench_tables.py --date {date} --tol {tol}\n")
        f.write("\\begin{table}[t]\n\\centering\n")
        f.write(f"\\caption{{cuHSDLP versus cuPDLPx at $10^{{{exponent}}}$ relative tolerance. "
                "Shifted geometric means use the Achterberg shifts ($s=10$ for time, "
                "$s=100$ for iterations); a solver that does not reach optimality is "
                "charged the wall-clock limit.  Ratios are cuHSDLP over cuPDLPx.}\n")
        f.write("\\label{tab:benchmark-summary}\n")
        f.write("\\begin{tabular}{lrrrrrrrrr}\n\\toprule\n")
        f.write("& & \\multicolumn{2}{c}{Solved} & \\multicolumn{3}{c}{SGM time (s)} "
                "& \\multicolumn{3}{c}{SGM iterations} \\\\\n")
        f.write("\\cmidrule(lr){3-4}\\cmidrule(lr){5-7}\\cmidrule(lr){8-10}\n")
        f.write("Suite & $n$ & cuHSDLP & cuPDLPx & cuHSDLP & cuPDLPx & ratio "
                "& cuHSDLP & cuPDLPx & ratio \\\\\n")
        f.write("\\midrule\n")
        for suite, st in per_suite.items():
            f.write("%s & %d & %d & %d & %.1f & %.1f & %.2f & %.0f & %.0f & %.2f \\\\\n" % summary_cells(suite, st))
        f.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n\n")

        f.write("\\begin{table}[t]\n\\centering\n")
        f.write("\\caption{Instances on which the two solvers reach different "
                "terminations.}\n\\label{tab:benchmark-disagreements}\n")
        f.write("\\begin{tabular}{llrlr}\n\\toprule\n")
        f.write("Instance & cuHSDLP & time (s) & cuPDLPx & time (s) \\\\\n\\midrule\n")
        for st in per_suite.values():
            for r in st["disagree"]:
                f.write("%s & %s & %.1f & %s & %.1f \\\\\n" % (
                    esc(r["instance"]), esc(r["HSD_status"]), r["HSD_time"], esc(r["PDLPx_status"]), r["PDLPx_time"]))
        f.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    print(f"  {path}")


def write_markdown(path, date, tol, per_suite):
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"# Benchmark summary: cuHSDLP vs cuPDLPx ({date}, tol {tol})\n\n")
        f.write("| Suite | n | solved HSD | solved PDLPx | SGM time HSD (s) | "
                "SGM time PDLPx (s) | time ratio | SGM iters HSD | SGM iters PDLPx | iter ratio |\n")
        f.write("|---|---|---|---|---|---|---|---|---|---|\n")
        for suite, st in per_suite.items():
            f.write("| %s | %d | %d | %d | %.1f | %.1f | %.2fx | %.0f | %.0f | %.2fx |\n" % summary_cells(suite, st))
        f.write("\nSGM population per suite: ")
        f.write(", ".join(f"{SUITE_LABEL[s]} {st['n_sgm']}/{st['n']}" for s, st in per_suite.items()))
        f.write("\n\n## Termination disagreements\n\n")
        f.write("| Suite | Instance | cuHSDLP | time (s) | iters | cuPDLPx | time (s) | iters |\n")
        f.write("|---|---|---|---|---|---|---|---|\n")
        for suite, st in per_suite.items():
            for r in st["disagree"]:
                f.write("| %s | %s | %s | %.1f | %d | %s | %.1f | %d |\n" % (
                    SUITE_LABEL[suite], r["instance"], r["HSD_status"], r["HSD_time"], r["HSD_iters"],
                    r["PDLPx_status"], r["PDLPx_time"], r["PDLPx_iters"]))
    print(f"  {path}")


def run(date, tol=DEFAULT_TOL, suites=tuple(SUITE_LABEL), output_dir=TABLE_DIR):
    output_dir.mkdir(parents=True, exist_ok=True)
    per_suite = {}
    for suite in suites:
        rows = load_comparison(suite, date)
        per_suite[suite] = {**summarize(rows), "disagree": [r for r in rows if r["HSD_status"] != r["PDLPx_status"]]}
    print(f"Writing tables for {date}:")
    write_latex(output_dir / f"benchmark_summary_{date}.tex", date, tol, per_suite)
    write_markdown(output_dir / f"benchmark_summary_{date}.md", date, tol, per_suite)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--date", required=True, help="cuHSDLP result date, e.g. 20260712")
    p.add_argument("--tol", default=DEFAULT_TOL, help="tolerance of the compared runs, as passed to bench_compare.py")
    p.add_argument("--suites", nargs="+", default=list(SUITE_LABEL), choices=sorted(SUITE_LABEL))
    p.add_argument("--output-dir", type=Path, default=TABLE_DIR)
    args = p.parse_args()
    run(args.date, args.tol, args.suites, args.output_dir)


if __name__ == "__main__":
    main()
